"""Main-text crossing table (d, alpha, L_s, paths, simulated crossing +- SE, predicted crossing, error) from archive_summary.json."""
import json
S = json.load(open(__import__("os").environ.get("SUMMARY", "archive_summary.json")))
TAGS = ["L2_a0.75_d128", "L2_a1_d128", "L2_a1.25_d128", "L3_a0.75_d128", "L3_a1_d128", "L3_a1.25_d128",
        "L2_a0.75_d256", "L2_a1_d256", "L2_a1.25_d256", "L3_a0.75_d256", "L3_a1_d256", "L3_a1.25_d256",
        "L2_a0.75_d512", "L2_a1_d512", "L2_a1.25_d512", "L3_a0.75_d512", "L3_a1_d512", "L3_a1.25_d512"]
def s(x):
    v = round(float(x), 1) + 0.0
    return f"${v:+.1f}$"
lines = ["% generated by make_main_table.py from archive_summary.json", "\\begin{tabular}{rrrrrrr}", "\\toprule",
         "$d$ & $\\alpha$ & $L_{\\mathrm{s}}$ & paths & simulation & prediction & error \\\\", "\\midrule"]
for t in TAGS:
    v = S[t]
    lines.append(f"{v['d']} & {v['alpha']:g} & {v['Ls']} & {v['R']} & {v['x_meas']:.0f} $\\pm$ {v['x_se']:.0f} & {v['x_pred']:.0f} & {s(100*(v['x_pred']-v['x_meas'])/v['x_meas'])}\\% \\\\")
lines += ["\\bottomrule", "\\end{tabular}"]
open("tables_out/main_crossing_table.tex", "w").write("\n".join(lines) + "\n")
print("written")
