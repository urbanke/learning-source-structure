"""Appendix regret table over all settings: unigram regret range, prediction error range, largest SE; copier regret
range, error range, largest SE, error relative to the regret. Reads summary_all.json; writes tables_out/regret_table_all.tex
and stats_all.json."""
import json, os
import numpy as np
S = json.load(open(os.environ.get("SUMMARY", "summary_all.json")))
def _rng(a, b, nd=1):
    a = round(float(a), nd) + 0.0; b = round(float(b), nd) + 0.0
    return f"$[{a:+.{nd}f},{b:+.{nd}f}]$"
lines = ["% generated by make_regret_table3.py from summary_all.json", "\\begin{tabular}{rrrrrrrrrr}", "\\toprule",
         "$L_{\\mathrm{s}}$ & $\\alpha$ & $d$ & \\unigram regret & error & SE & copier regret & error & SE & error/regret \\\\", "\\midrule"]
stats = {}; last = None
for v in sorted(S.values(), key=lambda v: (v["Ls"], v["alpha"], v["d"])):
    rows = v["rows"]
    Ferr = np.array([r["F_pred"] - r["F_meas"] for r in rows]); Cerr = np.array([r["C_pred"] - r["C_meas"] for r in rows])
    Cpct = 100 * Cerr / np.array([r["C_meas"] for r in rows])
    Fse = max(r["F_se"] for r in rows); Cse = max(r["C_se"] for r in rows)
    stats[v["tag"]] = dict(Ferr_max=float(np.abs(Ferr).max()), Fse_max=float(Fse), Cerr_min=float(Cerr.min()), Cerr_max=float(Cerr.max()),
                           Cpct_min=float(Cpct.min()), Cpct_max=float(Cpct.max()), Cse_max=float(Cse),
                           F_reg=(rows[0]["F_meas"], rows[-1]["F_meas"]), C_reg=(rows[0]["C_meas"], rows[-1]["C_meas"]), R=v["R"])
    if last is not None and v["Ls"] != last: lines.append("\\addlinespace[2pt]")
    last = v["Ls"]
    lines.append(f"{v['Ls']} & {v['alpha']:g} & {v['d']} & {rows[0]['F_meas']:.0f}--{rows[-1]['F_meas']:.0f} & {_rng(Ferr.min(), Ferr.max())} & {Fse:.1f} & "
                 f"{rows[0]['C_meas']:.0f}--{rows[-1]['C_meas']:.0f} & {_rng(Cerr.min(), Cerr.max(), 0)} & {Cse:.0f} & {_rng(Cpct.min(), Cpct.max())}\\% \\\\")
lines += ["\\bottomrule", "\\end{tabular}"]
os.makedirs("tables_out", exist_ok=True)
open("tables_out/regret_table_all.tex", "w").write("\n".join(lines) + "\n"); json.dump(stats, open("stats_all.json", "w"), indent=1)
print("\n".join(lines))
