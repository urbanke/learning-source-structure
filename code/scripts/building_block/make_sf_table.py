"""LaTeX table of the sampling-free crossings (sf_compare.json) for the settings with L_s <= 3."""
import json, os, sys
import numpy as np
S = json.load(open("sf_compare.json"))
tags = [t for t in S if S[t]["Ls"] <= 3 and S[t]["alpha"] <= 1.25]
tags.sort(key=lambda t: (S[t]["Ls"], S[t]["alpha"], S[t]["d"]))
lines = ["% generated by make_sf_table.py from sf_compare.json", "\\begin{tabular}{rrrrrrrrrr}", "\\toprule",
         "& & & \\multicolumn{3}{c}{crossing $n^*$} & \\multicolumn{2}{c}{no sampling vs} & \\multicolumn{2}{c}{cost difference}\\\\",
         "\\cmidrule(lr){4-6}\\cmidrule(lr){7-8}\\cmidrule(lr){9-10}",
         "$L_{\\mathrm{s}}$ & $\\alpha$ & $d$ & simulation & sampled & no sampling & sampled & simulation & copier & \\unigram\\\\",
         "\\midrule"]
rel_s = []; rel_m = []
for t in tags:
    v = S[t]
    if v["x_sf"] is None or v["x_sampled"] is None:
        continue
    a = f"{v['alpha']:g}"
    ds = 100 * (v["x_sf"] - v["x_sampled"]) / v["x_sampled"]; dm = 100 * (v["x_sf"] - v["x_meas"]) / v["x_meas"]
    rel_s.append(ds); rel_m.append(dm)
    lines.append(f"{v['Ls']} & {a} & {v['d']} & ${v['x_meas']:.0f}\\pm{v['x_se']:.0f}$ & ${v['x_sampled']:.0f}\\pm{v['x_pse']:.0f}$ & ${v['x_sf']:.0f}$ & ${ds:+.1f}\\%$ & ${dm:+.1f}\\%$ & ${int(round(v['dC'])):+d}$ & ${int(round(v['dF'])):+d}$\\\\")
lines += ["\\bottomrule", "\\end{tabular}"]
os.makedirs("repo_add/results/building_block", exist_ok=True)
open("repo_add/results/building_block/sampling_free_table.tex", "w").write("\n".join(lines) + "\n")
rs = np.abs(rel_s); rm = np.abs(rel_m)
print(f"{len(rel_s)} settings: |sf - sampled|: max {rs.max():.1f}%, median {np.median(rs):.1f}%, mean signed {np.mean(rel_s):+.1f}%; |sf - sim|: max {rm.max():.1f}%, median {np.median(rm):.1f}%, mean signed {np.mean(rel_m):+.1f}%")
print("dC range:", min(S[t]["dC"] for t in tags), max(S[t]["dC"] for t in tags), " dF range:", min(S[t]["dF"] for t in tags), max(S[t]["dF"] for t in tags))
print("seconds:", sorted(int(S[t]["seconds"]) for t in tags))
print("\n".join(lines))
