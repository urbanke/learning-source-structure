"""Main-text crossing table over all settings (L_s, alpha, d, paths, simulated crossing +- SE, prediction, error)
from summary_all.json; settings without a crossing in the window are listed in a separate line of the caption
(printed here). Writes tables_out/crossing_table_all.tex."""
import json, os
S = json.load(open(os.environ.get("SUMMARY", "summary_all.json")))
def s(x):
    v = round(float(x), 1) + 0.0
    return f"${v:+.1f}$"
rows = sorted(S.values(), key=lambda v: (v["Ls"], v["alpha"], v["d"]))
lines = ["% generated by make_table3.py from summary_all.json", "\\begin{tabular}{rrrrrrr}", "\\toprule",
         "$L_{\\mathrm{s}}$ & $\\alpha$ & $d$ & paths & simulation & prediction & error \\\\", "\\midrule"]
last = None; none = []
for v in rows:
    if v["x_meas"] is None or v["x_pred"] is None:
        none.append(v); continue
    if last is not None and v["Ls"] != last:
        lines.append("\\addlinespace[2pt]")
    last = v["Ls"]
    lines.append(f"{v['Ls']} & {v['alpha']:g} & {v['d']} & {v['R']} & {v['x_meas']:.0f} $\\pm$ {v['x_se']:.0f} & {v['x_pred']:.0f} $\\pm$ {v['x_pse']:.0f} & {s(100*(v['x_pred']-v['x_meas'])/v['x_meas'])}\\% \\\\")
lines += ["\\bottomrule", "\\end{tabular}"]
os.makedirs("tables_out", exist_ok=True)
open("tables_out/crossing_table_all.tex", "w").write("\n".join(lines) + "\n")
print("\n".join(lines)); print("no crossing:", [(v["tag"], v["x_meas"], v["x_pred"]) for v in none])
