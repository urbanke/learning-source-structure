"""Empirical scaling of the crossing n*(d, alpha, L_s) from the takeover grid (results/takeover_all.json: crossing of
the seed-averaged gap, 16 seeds per setting, d up to 32768) together with the predictions (Table 1 and the
sampling-free sweeps sfx_<tag>.json at small d).  Writes scaling_exponents.json, scaling_exponents.tex and the
figure scaling_figure.pdf (top row: n* against d; bottom row: n* against the source depth).
Usage: python3 scaling_laws.py [takeover_all.json] [summary_all.json]"""
import sys, json, glob, os, collections
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
plt.rcParams.update({"font.size": 8, "axes.titlesize": 9, "axes.labelsize": 8.5, "legend.fontsize": 7.5})

tak = json.load(open(sys.argv[1] if len(sys.argv) > 1 else "takeover_all.json"))
summ = json.load(open(sys.argv[2] if len(sys.argv) > 2 else "summary_all.json"))
DMIN_FIT = 256   # smallest alphabet size in the power-law fits (the local slope still varies below)
NMIN_FIT = 1000  # smallest crossing in the fits (below, the dip of the gap is shallow and the 16-seed mean is noisy)

# --- the simulated crossings (takeover grid) -------------------------------------------------------------------
sim = collections.defaultdict(dict)          # (alpha, L) -> {d: n*}
for e in tak:
    if e["mean_lambda_crossing"] and e["n_censored"] == 0:
        sim[(e["alpha"], e["L"])][e["d"]] = e["mean_lambda_crossing"]

# --- the predictions: Table 1 (sampled matrices) and the sampling-free sweeps -----------------------------------
pred = collections.defaultdict(dict)         # (alpha, L) -> {d: n*_pred}
for tag, v in summ.items():
    if v.get("x_pred"):
        pred[(v["alpha"], v["Ls"])][v["d"]] = v["x_pred"]
sf = collections.defaultdict(dict)
for f in glob.glob("sfx_L*_a*_d*.json"):
    v = json.load(open(f))
    if v.get("x_sf"):
        sf[(v["alpha"], v["Ls"])][v["d"]] = v["x_sf"]

# --- power-law fits in d at fixed (alpha, L) ----------------------------------------------------------------------
fits = []
for (alpha, L), pts in sorted(sim.items()):
    ds = np.array(sorted(d for d in pts if d >= DMIN_FIT and pts[d] >= NMIN_FIT), float)
    if len(ds) < 3:
        continue
    y = np.log([pts[int(d)] for d in ds]); x = np.log(ds)
    b, a = np.polyfit(x, y, 1)
    resid = y - (a + b * x); sl = np.diff(y) / np.diff(x)
    fits.append(dict(alpha=alpha, L=L, d_min=int(ds[0]), d_max=int(ds[-1]), n_d=len(ds), exponent=float(b), log10_C=float(a / np.log(10)),
                     max_rel_resid=float(np.abs(np.exp(resid) - 1).max()), slope_last=float(sl[-1]), slope_first=float(sl[0])))
json.dump(dict(dmin_fit=DMIN_FIT, nmin_fit=NMIN_FIT, fits=fits), open("scaling_exponents.json", "w"), indent=1)

# table: exponent by alpha (rows) and L (columns) for L <= 8
alphas = sorted(set(f["alpha"] for f in fits)); Ls = [L for L in (1, 2, 3, 4, 5, 6) if any(f["L"] == L for f in fits)]
lines = ["%% generated by scaling_laws.py from takeover_all.json (crossing of the seed-averaged gap, 16 seeds); fits over d >= %d, n* >= %d" % (DMIN_FIT, NMIN_FIT),
         "\\begin{tabular}{l" + "r" * len(Ls) + "}", "\\toprule", "$\\alpha$ & " + " & ".join(f"$L_{{\\mathrm{{s}}}}={L}$" for L in Ls) + "\\\\", "\\midrule"]
for alpha in alphas:
    cells = []
    for L in Ls:
        f = [f for f in fits if f["alpha"] == alpha and f["L"] == L]
        cells.append(f"{f[0]['exponent']:.2f}" if f else "--")
    lines.append(f"{alpha:g} & " + " & ".join(cells) + "\\\\")
lines += ["\\bottomrule", "\\end{tabular}"]
open("scaling_exponents.tex", "w").write("\n".join(lines) + "\n")

# --- figure: top row n* against d (L_s = 2, 3), bottom row n* against L_s (d = 256, 2048), lines per alpha -----
cols = {0.5: "#1b9e77", 0.75: "#d95f02", 1.0: "#7570b3", 1.25: "#e7298a", 1.5: "#66a61e"}
fig, axes = plt.subplots(2, 2, figsize=(6.4, 5.0))
for ax, L in zip(axes[0], (2, 3)):
    for alpha in (0.5, 0.75, 1.0, 1.25, 1.5):
        pts = sim.get((alpha, L), {})
        if not pts:
            continue
        ds = sorted(pts); ax.plot(ds, [pts[d] for d in ds], "o", color=cols[alpha], ms=3.5, label=f"$\\alpha={alpha:g}$")
        f = [f for f in fits if f["alpha"] == alpha and f["L"] == L]
        if f:
            xx = np.array([f[0]["d_min"], f[0]["d_max"]]); ax.plot(xx, 10 ** f[0]["log10_C"] * xx ** f[0]["exponent"], "-", color=cols[alpha], lw=1)
            xd = np.array([min(ds), f[0]["d_min"]]); ax.plot(xd, 10 ** f[0]["log10_C"] * xd ** f[0]["exponent"], ":", color=cols[alpha], lw=1)
        pp = dict(sf.get((alpha, L), {})); pp.update(pred.get((alpha, L), {}))   # the prediction: sampled matrices where available, else no sampling
        ax.plot(sorted(pp), [pp[d] for d in sorted(pp)], "x", color=cols[alpha], ms=7, mew=1.5)
    ax.set_xscale("log", base=2); ax.set_yscale("log"); ax.set_xlabel("$d$"); ax.set_title(f"$L_{{\\mathrm{{s}}}}={L}$")
    ax.grid(True, which="major", alpha=0.3)
axes[0, 1].sharey(axes[0, 0])
axes[0, 0].set_ylabel("crossing $n^*$"); axes[0, 0].legend(loc="upper left")
h = [axes[0, 1].plot([], [], "ko", ms=3.5, label="simulation")[0], axes[0, 1].plot([], [], "kx", ms=7, mew=1.5, label="prediction")[0],
     axes[0, 1].plot([], [], "k-", lw=1, label="power fit")[0]]
axes[0, 1].legend(handles=h, loc="lower right", frameon=False)
for ax, d in zip(axes[1], (256, 2048)):
    for alpha in (0.5, 0.75, 1.0, 1.25, 1.5):
        pts = {L: sim[(alpha, L)][d] for (a, L) in sim if a == alpha and d in sim[(alpha, L)]}
        if pts:
            Ls_ = sorted(pts); ax.plot(Ls_, [pts[L] for L in Ls_], "o-", color=cols[alpha], ms=4, lw=1, label=f"$\\alpha={alpha:g}$")
    ax.set_yscale("log"); ax.set_xlabel("source depth $L_{\\mathrm{s}}$"); ax.set_title(f"$d={d}$"); ax.grid(True, alpha=0.3)
axes[1, 0].set_ylabel("crossing $n^*$")
fig.tight_layout(); fig.savefig("scaling_figure.pdf"); fig.savefig("scaling_figure.png", dpi=110)

# --- console summary ------------------------------------------------------------------------------------------------
print("exponents of n* in d (fits over d >= %d, n* >= %d):" % (DMIN_FIT, NMIN_FIT))
for f in fits:
    if f["L"] <= 8:
        print(f"  alpha={f['alpha']:<5} L={f['L']:<2}: {f['exponent']:.2f}  (d {f['d_min']}..{f['d_max']}, {f['n_d']} pts, max rel. resid {100*f['max_rel_resid']:.0f}%, first/last slope {f['slope_first']:.2f}/{f['slope_last']:.2f})")
print("rule min(2, 1/2 + 1/alpha):", {a: round(min(2.0, 0.5 + 1.0 / a), 2) for a in alphas})
# depth: log-ratio per unit of L between L = 2 and 6 at d = 2048
for alpha in (0.5, 0.75, 1.0, 1.5):
    pts = {L: sim[(alpha, L)][2048] for (a, L) in sim if a == alpha and 2048 in sim[(alpha, L)]}
    Ls_ = [L for L in (2, 3, 4, 5, 6, 8) if L in pts]
    if len(Ls_) >= 2:
        r = np.polyfit(Ls_, np.log([pts[L] for L in Ls_]), 1)[0]
        print(f"  d=2048 alpha={alpha}: n* falls by a factor {np.exp(-r):.2f} per unit of L_s (L_s in {Ls_})")
