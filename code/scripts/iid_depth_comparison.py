"""Paper comparisons for the finite-alphabet iid learning-cost formula.

OPENBLAS_NUM_THREADS=1 python code/scripts/iid_depth_comparison.py --run --collect --plot

The full command measures depths one and six and reuses the archived depth-three
experiment. Predictions are independent and must first be
generated by iid_depth_prediction.py. Raw draws remain in ignored output/.
Use --collect --plot to rebuild the small paper outputs from existing runs.
"""
from __future__ import annotations

import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
from pathlib import Path
import subprocess
import sys

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.ticker import FixedLocator, FuncFormatter, NullFormatter
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
RESULT = ROOT / 'results/mechanism/iid_depth_comparison.json'
DEPTHS = (1, 3, 6)
ALPHAS = (.5, 1., 1.5, 2.)
DS = (256, 4096)
KS = (256, 1024, 4096, 16384)


def load(path):
    return json.loads(Path(path).read_text())


def run():
    def one(setting):
        depth,alpha=setting
        reps=512 if depth==1 else 256
        path = ROOT / f'output/iid_depth_coverage_long/L{depth}_a{alpha:g}.json'
        if path.exists() and load(path).get('complete'):
            existing=load(path)
            assert existing['seed']==202609069 and existing['repetition_start']==0, path
            assert {c['d'] for c in existing['cells']}==set(DS), path
            assert all(c['L']==depth and c['alpha']==alpha and c['reps']<=reps
                       and c['k']==list(KS) for c in existing['cells']), path
            if all(c['reps']==reps for c in existing['cells']):
                return
        subprocess.run([sys.executable, str(Path(__file__).with_name('iid_alpha15_followup.py')),
            '--L', str(depth), '--alpha', str(alpha), '--ds', '256', '4096',
            '--ks', *map(str, KS), '--reps', str(reps), '--seed', '202609069',
            '--step', str(1/128), '--skip-original-prediction', '--out', str(path)],
            cwd=ROOT, check=True)
    with ThreadPoolExecutor(max_workers=2) as pool:
        list(pool.map(one, [(L,a) for L in (1,6) for a in ALPHAS]))


def collect():
    sources = [ROOT / 'results/mechanism/iid_layered_tilt_check.json']
    sources += [ROOT / f'output/iid_depth_coverage_long/L{L}_a{a:g}.json'
                for L in (1,6) for a in ALPHAS]
    rows = []
    for path in sources:
        data = load(path)
        if 'complete' in data:
            assert data['complete'], path
        for c in data.get('cells', data.get('rows', [])):
            if c['d'] not in DS or c['alpha'] not in ALPHAS or c['L'] not in DEPTHS:
                continue
            means = c.get('redundancy_mean', c.get('redundancy_mean_bits'))
            ses = c.get('redundancy_se', c.get('redundancy_se_bits'))
            for k in KS:
                i = c['k'].index(k)
                rows.append(dict(L=c['L'], d=c['d'], alpha=c['alpha'], k=k,
                    repetitions=c.get('reps', c.get('repetitions')),
                    measured_mean_bits=means[i], measured_SE_bits=ses[i],
                    source=str(path.relative_to(ROOT))))
    prediction_path = ROOT / 'results/mechanism/iid_depth_prediction.json'
    prediction = load(prediction_path)
    keyed = {(r['L'], r['d'], r['alpha'], r['k']): r for r in prediction['rows']}
    for row in rows:
        p = keyed[row['L'], row['d'], row['alpha'], row['k']]
        mean, se = p['finite_random_scale']['mean_bits'], p['finite_random_scale']['SE_bits']
        measured, mse = row['measured_mean_bits'], row['measured_SE_bits']
        row.update(prediction_mean_bits=mean, prediction_SE_bits=se,
                   original_sum_bits=p['original_sum_bits'],
                   difference_bits=measured-mean,
                   difference_SE_bits=float(np.hypot(mse, se)),
                   relative_difference=measured/mean-1,
                   difference_in_combined_SE=(measured-mean)/np.hypot(mse, se),
                   prediction_draws=p['draws'])
    rows.sort(key=lambda r: (r['L'], r['alpha'], r['d'], r['k']))
    assert len(rows) == len(DEPTHS)*len(ALPHAS)*len(DS)*len(KS)
    assert len({(r['L'],r['d'],r['alpha'],r['k']) for r in rows}) == len(rows)
    def stats(rr):
        return dict(points=len(rr),
            maximum_absolute_relative_difference=max(abs(r['relative_difference']) for r in rr),
            maximum_absolute_difference_in_combined_SE=max(abs(r['difference_in_combined_SE']) for r in rr),
            within_two_combined_SE=int(sum(abs(r['difference_in_combined_SE']) <= 2 for r in rr)),
            within_three_combined_SE=int(sum(abs(r['difference_in_combined_SE']) <= 3 for r in rr)))
    summaries = {f'L{L}': stats([r for r in rows if r['L']==L]) for L in DEPTHS}
    summaries['all'] = stats(rows)
    summaries['k_at_least_256'] = stats([r for r in rows if r['k']>=256])
    summaries['k_equals_d'] = stats([r for r in rows if r['k']==r['d']])
    result = dict(schema_version=1, target='Expected iid Bayes redundancy with q and generating depth known',
        source_depths=DEPTHS, alphabet_sizes=DS, tilts=ALPHAS, sample_lengths=KS,
        qualifications=[
            'Finite prediction T retains the random normalizer and finite rank sum. No parameters fitted.',
            'The uniform additive theorem is for fixed alpha>1 and fixed L; alpha<=1 are separate numerical comparisons.',
            'Prediction normalizer draws are independent of source/sample measurements; difference SE includes both.',
            'Sample checkpoints and some alphabets/tilts share draws; these are not independent hypothesis tests.',
            'Scalar quadrature/interpolation checks are separate from Monte Carlo standard errors.',
            'This experiment is iid and matched-prior Bayes, not the symmetric depth-mixture copying algorithm or a chain.'],
        sources=[dict(path=str(p.relative_to(ROOT)), sha256=hashlib.sha256(p.read_bytes()).hexdigest())
                 for p in sources+[prediction_path]],
        new_measurement_runs=[dict(source=str(p.relative_to(ROOT)),
            command_argv=load(p)['command_argv'], seed=load(p)['seed'],
            repetition_start=load(p)['repetition_start'],
            outer_refinement_maximum_bits=max(c['maximum_outer_refinement_difference_bits']
                                              for c in load(p)['cells'])) for p in sources[1:]],
        summaries=summaries, rows=rows)
    RESULT.write_text(json.dumps(result, indent=2)+'\n')
    table = [r'\begin{tabular}{c rr rr rr}', r'\toprule',
             r'& \multicolumn{2}{c}{$L=1$} & \multicolumn{2}{c}{$L=3$} & \multicolumn{2}{c}{$L=6$}\\',
             r'\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}',
             r'$\alpha$ & Uncorrected & Finite & Uncorrected & Finite & Uncorrected & Finite\\', r'\midrule']
    for a in ALPHAS:
        vals = []
        for L in DEPTHS:
            r = next(r for r in rows if (r['L'],r['alpha'],r['d'],r['k'])==(L,a,4096,4096))
            vals.extend([100*(r['measured_mean_bits']/r['original_sum_bits']-1),100*r['relative_difference']])
        table.append(f'{a:g} & '+' & '.join(f'${v:+.1f}\\%$' if abs(v)>=.05 else '$0.0\\%$' for v in vals)+r'\\')
    table += [r'\bottomrule',r'\end{tabular}']
    (ROOT/'results/mechanism/iid_depth_comparison_table.tex').write_text('\n'.join(table)+'\n')
    print(json.dumps(summaries, indent=2))


def style():
    plt.rcParams.update({'font.family':'serif', 'font.size':8, 'axes.labelsize':8,
        'axes.titlesize':9, 'xtick.labelsize':7, 'ytick.labelsize':7,
        'legend.fontsize':8, 'axes.spines.top':False, 'axes.spines.right':False,
        'pdf.fonttype':42})


def plot():
    style()
    rows = load(RESULT)['rows']
    fig, axs = plt.subplots(3,4,figsize=(6.5,5.4),sharex=True)
    colors = ('#2369a0', '#ba5b23')
    for i,L in enumerate(DEPTHS):
        for j,a in enumerate(ALPHAS):
            ax=axs[i,j]
            for d,color in zip(DS,colors):
                rr=[r for r in rows if r['L']==L and r['alpha']==a and r['d']==d]
                x=np.array([r['k'] for r in rr]); y=np.array([r['measured_mean_bits'] for r in rr])
                m=np.array([r['prediction_mean_bits'] for r in rr]); se=np.array([r['prediction_SE_bits'] for r in rr])
                ax.plot(x,m,color=color,lw=1.3)
                ax.fill_between(x,m-2*se,m+2*se,color=color,alpha=.12,lw=0)
                ax.errorbar(x,y,yerr=2*np.array([r['measured_SE_bits'] for r in rr]),
                    fmt='o',ms=3,mfc='white',mec=color,color=color,elinewidth=.65,capsize=1.5)
            ax.set_xscale('log',base=4); ax.set_yscale('log')
            ax.set_xlim(128,32768)
            ax.set_xticks([256,2048,16384],['256','2048','16384'])
            ax.yaxis.set_major_locator(FixedLocator([3,10,30,100,300,1000,3000,10000]))
            ax.yaxis.set_major_formatter(FuncFormatter(lambda x,_:f'{x:g}'))
            ax.yaxis.set_minor_formatter(NullFormatter())
            ax.grid(alpha=.16,which='major',lw=.5)
            if i==0:ax.set_title(r'$\alpha='+f'{a:g}'+r'$')
            if j==0:ax.set_ylabel(r'$L='+str(L)+r'$'+'\nLearning cost (bits)')
            if i==2:ax.set_xlabel('Samples $k$')
    fig.legend(handles=[Line2D([],[],color=colors[0],label='$d=256$'),
                        Line2D([],[],color=colors[1],label='$d=4096$'),
                        Line2D([],[],color='.2',marker='o',mfc='white',ls='none',label='Simulation: mean $\\pm 2$ SE'),
                        Line2D([],[],color='.2',label='Finite-alphabet prediction')],
               loc='upper center',bbox_to_anchor=(.53,1.005),ncol=2,frameon=False,
               columnspacing=1.5,handlelength=2)
    fig.subplots_adjust(left=.10,right=.975,bottom=.085,top=.875,wspace=.38,hspace=.28)
    fig.savefig(ROOT / 'figures/iid_depth_comparison.pdf')
    plt.close(fig)

    data=load(ROOT / 'results/mechanism/iid_alpha15_followup.json')
    pred=load(ROOT / 'results/mechanism/iid_tilt_finite_prediction.json')
    fig,axs=plt.subplots(1,2,figsize=(6.5,2.45),sharex=True)
    ds=[4096,16384,65536,262144]
    for ax,k in zip(axs,[4096,16384]):
        means=[]; errors=[]; predicted=[]; pses=[]
        for d in ds:
            c=next(c for c in data['cells'] if c['alpha']==1.5 and c['d']==d)
            ix=c['k'].index(k); means.append(c['redundancy_mean'][ix]); errors.append(c['redundancy_se'][ix])
            p=next(r for r in pred['rows'] if r['alpha']==1.5 and r['d']==d and r['k']==k)
            predicted.append(p['finite_random_scale']['mean_bits']); pses.append(p['finite_random_scale']['SE_bits'])
        predicted=np.array(predicted); pses=np.array(pses)
        ax.plot(ds,predicted,color=colors[0],lw=1.4)
        ax.fill_between(ds,predicted-2*pses,predicted+2*pses,color=colors[0],alpha=.12,lw=0)
        ax.errorbar(ds,means,yerr=2*np.array(errors),fmt='o',color='black',mfc='white',ms=3.5,capsize=2,lw=.8)
        # The constant is independently calculated in the archived tail check.
        constant=next(c['coefficient_bits'] for c in
            load(ROOT / 'results/mechanism/iid_tilt_tail_check.json')['constants'] if c['alpha']==1.5)
        ax.axhline(constant*k**(2/3),color=colors[1],ls='--',lw=1.2)
        ax.set_xscale('log',base=4)
        ax.set_xlim(2800,400000)
        ax.set_xticks(ds,['4,096','16,384','65,536','262,144'])
        ax.set_title(f'$k={k:,}$'); ax.set_xlabel('Alphabet size $d$')
        ax.grid(alpha=.15,lw=.5)
    axs[0].set_ylabel('Learning cost (bits)')
    fig.legend(handles=[Line2D([],[],color='black',marker='o',mfc='white',ls='none',label='Simulation'),
                        Line2D([],[],color=colors[0],label='Finite-alphabet prediction'),
                        Line2D([],[],color=colors[1],ls='--',label=r'Infinite-alphabet leading term: $A_{1.5,3}k^{2/3}$')],
               loc='upper center',bbox_to_anchor=(.54,1.0),ncol=1,frameon=False,
               handlelength=2,borderaxespad=0,labelspacing=.25)
    fig.subplots_adjust(left=.09,right=.975,bottom=.22,top=.67,wspace=.25)
    fig.savefig(ROOT / 'figures/iid_finite_alphabet_comparison.pdf')
    plt.close(fig)


if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--run',action='store_true')
    ap.add_argument('--collect',action='store_true')
    ap.add_argument('--plot',action='store_true')
    args=ap.parse_args()
    if args.run: run()
    if args.collect: collect()
    if args.plot: plot()
