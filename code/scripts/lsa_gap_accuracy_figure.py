"""Plot the proved LSA gap approximation against saved chain means.

MPLCONFIGDIR=/tmp/lsa-mpl OPENBLAS_NUM_THREADS=1 python code/scripts/lsa_gap_accuracy_figure.py

Uses committed predictions and saved16-source means; no new samples or fits.
The extra d128 checkpoints are regenerated by:
OPENBLAS_NUM_THREADS=1 OMP_NUM_THREADS=1 python code/scripts/lsa_parameter_gap.py --d 128 --rmax 2048 --step .03 --indices 0 1 --out results/mechanism/lsa_gap_accuracy_extra_d128.json
"""
from pathlib import Path
import json, hashlib
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.ticker import FuncFormatter, MaxNLocator
ROOT=Path(__file__).resolve().parents[2]

def crossing(x,y):
    crossings=[]
    for a in range(len(x)-1):
        if y[a]<=0<y[a+1]:
            crossings.append(float(x[a]+(x[a+1]-x[a])*(-y[a])/(y[a+1]-y[a])))
    if not crossings:raise ValueError('No bracketed crossing')
    return crossings[-1]

saved_path=ROOT/'results/mechanism/crossing_finite_count_prediction.json'
saved=json.loads(saved_path.read_text())
plt.rcParams.update({'font.family':'DejaVu Sans','font.size':9,'axes.spines.top':False,'axes.spines.right':False})
fig,axes=plt.subplots(1,2,figsize=(7.0,2.95),layout='constrained')
summary=[]
for ax,d in zip(axes,[128,512]):
    pred_path=ROOT/f'results/mechanism/lsa_parameter_gap_d{d}_Ls2.json'
    prediction=json.loads(pred_path.read_text())['rows']
    if d==128:prediction+=json.loads((ROOT/'results/mechanism/lsa_gap_accuracy_extra_d128.json').read_text())['rows']
    prediction=sorted(prediction,key=lambda r:r['n'])
    x=np.array([r['n'] for r in prediction]);y=np.array([r['integer_interpolated_gap_bits'] for r in prediction])
    cell=next(c for c in saved['cells'] if(c['d'],c['alpha'],c['L'])==(d,.75,2))
    sx=np.asarray(cell['tokens']);sy=np.asarray(cell['chain']['gap']['mean']);se=np.asarray(cell['chain']['gap']['SE'])
    lower,upper=(454,2268) if d==128 else (17629,29381)
    mask=(sx>=lower)&(sx<=upper);pmask=(x>=lower)&(x<=upper)
    predicted=crossing(x,y);measured=crossing(sx,sy)
    ax.axhline(0,color='.5',lw=.7)
    ax.plot(x[pmask],y[pmask],color='#1f5b9b',lw=1.7,label='Predicted difference')
    ax.errorbar(sx[mask],sy[mask],yerr=2*se[mask],fmt='o',ms=3.2,color='#333333',capsize=2,lw=.85,label='Simulation mean ± 2 SE')
    ax.axvline(predicted,color='#1f5b9b',ls=':',lw=.85,alpha=.7)
    ax.axvline(measured,color='#333333',ls=':',lw=.85,alpha=.7)
    ax.set_xlabel('Sequence length (tokens)')
    ax.xaxis.set_major_locator(MaxNLocator(4));ax.xaxis.set_major_formatter(FuncFormatter(lambda v,pos:f'{v:,.0f}'))
    ax.grid(axis='y',alpha=.14)
    summary.append(dict(d=d,alpha=.75,source_depth=2,predicted_crossing=predicted,measured_crossing=measured,relative_crossing_error_percent=100*(predicted/measured-1),source_repetitions=cell['repetitions'],formula_input_sha256=hashlib.sha256(pred_path.read_bytes()).hexdigest()))
axes[0].set_ylabel('Unigram cost − copier cost (bits)')
handles,labels=axes[0].get_legend_handles_labels();fig.legend(handles,labels,loc='outside upper center',ncol=2,frameon=False,fontsize=9)
fig.savefig(ROOT/'results/mechanism/lsa_gap_accuracy.png',dpi=260)
plt.close(fig)
(ROOT/'results/mechanism/lsa_gap_accuracy.json').write_text(json.dumps(dict(cases=summary,scope='Two illustrative finite comparisons, alpha.75 source depth2. Crossing estimates use linear interpolation between evaluated points. No fitted parameters or new source/sequence samples.',saved_input_sha256=hashlib.sha256(saved_path.read_bytes()).hexdigest()),indent=2)+'\n')
rows=[r'\begin{tabular}{rrrr}',r'\toprule',r'$d$ & Predicted crossing & Measured crossing & Timing error \\',r'\midrule']
for r in summary:rows.append(f'{r["d"]} & {r["predicted_crossing"]:,.0f} & {r["measured_crossing"]:,.0f} & {r["relative_crossing_error_percent"]:.1f}\\% \\\\')
rows += [r'\bottomrule',r'\end{tabular}']
(ROOT/'results/mechanism/lsa_gap_accuracy_table.tex').write_text('\n'.join(rows)+'\n')
print(json.dumps(summary,indent=2))
