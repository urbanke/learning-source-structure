"""Sampling-free approximation to the unigram LSA codelength.

The source is exactly the random Markov source in mechanisms.tex.  Its rows
are independent copies of

    R_b = q_b G_b / sum_c q_c G_c,

where G_b is a product of ``source_depth`` mean-one exponentials.  Row raw
moments through order four are evaluated by one-dimensional gamma integrals.
They give the exact mean and covariance of the second-order finite-occupation
expansion in equations documented by ``finite_occupation_moments`` below.

Each marginal occupation probability is then closed by the beta distribution
with those two moments.  The resulting beta-binomial probabilities give a
deterministic mean count profile.  The full symmetric LSA depth mixture is
evaluated at that profile.  No source table, path, count vector, or Monte Carlo
sample is generated by this script.  Saved simulations may be read solely for
validation.

Only an existing sealed LSA moment store is read.  Nothing is provisioned.
"""
from __future__ import annotations

