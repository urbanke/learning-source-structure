import hashlib
import json
import math
from pathlib import Path
import sys
import time

import numpy as np
from scipy.special import betaln, gammaln, logsumexp
from scipy.stats import binom

from tilted_row_reference import DEFAULT_STORE, configure_store


ROOT = Path(__file__).resolve().parents[2]
LN2 = math.log(2.0)
EULER = 0.5772156649015329


def zipf_law(d: int, alpha: float) -> np.ndarray:
    if d < 2 or alpha < 0:
        raise ValueError("Require d >= 2 and alpha >= 0")
    q = np.arange(1, d + 1, dtype=float) ** (-alpha)
    return q / q.sum()


def _log_phi(tables, depth: int, order: int, values: np.ndarray) -> np.ndarray:
    if depth == 0:
        # At source depth zero the unnormalised weight is deterministically one.
        return -np.exp(values)
    if depth == 1:
        return gammaln(order + 1) - (order + 1) * np.logaddexp(0.0, values)
    return tables.log_phi(depth, order, values)


def _trapezoid_log_weights(grid: np.ndarray) -> np.ndarray:
    widths = np.empty_like(grid)
    widths[1:-1] = (grid[2:] - grid[:-2]) / 2
    widths[0] = (grid[1] - grid[0]) / 2
    widths[-1] = (grid[-1] - grid[-2]) / 2
    return np.log(widths)


def source_row_moments(q: np.ndarray, source_depth: int, tables, *,
                       step: float = 1 / 32, lower: float = -48.0,
                       upper: float = 44.0, batch_size: int = 32) -> dict:
    """Return row moments needed for the second-order occupation formula.

    If r is a multi-index and |r| > 0, the raw row moment is

      E prod_b R_b**r_b = prod_b q_b**r_b / Gamma(|r|)
          * integral s**(|r|-1) prod_b phi[L_s,r_b](s q_b) ds.

    The calculation below evaluates all one-coordinate moments through order
    four and the pair moments (1,1), (1,2), and (2,2).  Rank-one quadrature
    contractions make its cost O(number_of_grid_points * d**2), rather than
    one separate integral per tensor entry.
    """
    q = np.asarray(q, dtype=float)
    if q.ndim != 1 or len(q) < 2 or np.any(q <= 0) or not np.isclose(q.sum(), 1):
        raise ValueError("q must be a strictly positive probability vector")
    if source_depth < 0 or int(source_depth) != source_depth:
        raise ValueError("source_depth must be a nonnegative integer")
    if step <= 0 or lower >= upper:
        raise ValueError("Invalid quadrature grid")
    d = len(q)
    grid = np.arange(lower, upper + step / 2, step)
    log_widths = _trapezoid_log_weights(grid)
    logq = np.log(q)
    log_phi = []
    for order in range(5):
        values = np.empty((d, len(grid)))
        for start in range(0, d, batch_size):
            stop = min(start + batch_size, d)
            shifted = (grid[None, :] + logq[start:stop, None]).ravel()
            values[start:stop] = _log_phi(
                tables, source_depth, order, shifted).reshape(stop - start, -1)
        log_phi.append(values)
    zero = log_phi[0]
    zero_sum = zero.sum(axis=0)
    powers = [np.ones_like(zero)]
    for order in range(1, 5):
        powers.append(np.exp(order * logq[:, None] + log_phi[order] - zero))

    endpoint_drops = []

    def weight(total_order: int) -> tuple[np.ndarray, float]:
        logw = (total_order * grid + zero_sum - gammaln(total_order)
                + log_widths)
        peak = float(np.max(logw))
        endpoint_drops.append(peak - float(max(logw[0], logw[-1])))
        return np.exp(logw - peak), math.exp(peak)

    def one(order: int) -> np.ndarray:
        w, scale = weight(order)
        return scale * (powers[order] @ w)

    def pair(left_order: int, right_order: int) -> np.ndarray:
        total = left_order + right_order
        w, scale = weight(total)
        result = scale * ((powers[left_order] * w) @ powers[right_order].T)
        diagonal = one(total)
        result[np.diag_indices(d)] = diagonal
        return result

    mu = one(1)
    raw2 = one(2)
    raw3 = one(3)
    raw4 = one(4)
    raw11 = pair(1, 1)
    raw12 = pair(1, 2)  # entry (i,b) is E[R_i R_b^2]
    raw22 = pair(2, 2)

    K = raw11 - np.outer(mu, mu)
    # H[i,b] = E[(R_i-mu_i)(R_b-mu_b)^2] = C_{b i b}.
    H = (raw12 - np.outer(mu, raw2) - 2 * raw11 * mu[None, :]
         + 2 * np.outer(mu, mu ** 2))
    # Dpair[i,b] = E[(R_i-mu_i)^2(R_b-mu_b)^2] = D_{i i b b}.
    raw21 = raw12.T
    Dpair = (raw22 - 2 * raw21 * mu[None, :] - 2 * raw12 * mu[:, None]
             + raw2[:, None] * mu[None, :] ** 2
             + mu[:, None] ** 2 * raw2[None, :]
             + 4 * raw11 * np.outer(mu, mu)
             - 3 * np.outer(mu ** 2, mu ** 2))

    # Replace the diagonals by the direct one-coordinate central moments.
    diagonal = np.diag_indices(d)
    K[diagonal] = raw2 - mu ** 2
    H[diagonal] = raw3 - 3 * mu * raw2 + 2 * mu ** 3
    Dpair[diagonal] = raw4 - 4 * mu * raw3 + 6 * mu ** 2 * raw2 - 3 * mu ** 4

    diagnostics = dict(
        source_depth=int(source_depth), alphabet_size=d, integration_step=step,
        integration_interval=[lower, upper], integration_points=len(grid),
        minimum_log_weight_endpoint_drop=float(min(endpoint_drops)),
        row_mean_sum_error=float(abs(mu.sum() - 1)),
        maximum_row_covariance_sum_error=float(np.max(abs(K.sum(axis=1)))),
        minimum_row_variance=float(np.min(np.diag(K))),
        maximum_row_variance=float(np.max(np.diag(K))),
        qualification=("Raw moments are one-dimensional integrals evaluated "
                       "by trapezoidal quadrature; endpoint drops are numerical "
                       "diagnostics, not certified error bounds."))
    return dict(mu=mu, K=K, third_bib=H, fourth_iibb=Dpair,
                raw2=raw2, raw3=raw3, raw4=raw4, diagnostics=diagnostics)


def finite_occupation_moments(q: np.ndarray, k: int, row: dict) -> dict:
    """Exact moments of the second-order finite-occupation expansion.

    Write T = 1 mu + A.  The conditional mean token law is

      pbar_k(T) = k^{-1} q sum_{s=0}^{k-1} T^s.

    Keeping its terms through A^2 gives

      ptilde_k = b + u A + v A^2,

    where b, u, and v below are row vectors.  The returned mean and covariance
    are exact for ptilde_k under the random-table law; no independence closure
    is made in this function.  Row independence leaves only equal-row and
    paired-row contractions in the fourth moment.
    """
    if not isinstance(k, (int, np.integer)) or k < 1:
        raise ValueError("k must be a positive integer")
    q = np.asarray(q, dtype=float)
    mu, K = row["mu"], row["K"]
    Cbib, Diibb = row["third_bib"], row["fourth_iibb"]
    b = (q + (k - 1) * mu) / k
    u = np.zeros_like(q) if k < 2 else (q + (k - 2) * mu) / k
    v = np.zeros_like(q) if k < 3 else (q + (k - 3) * mu) / k
    g = v @ K
    mean = b + g
    trace_K = float(np.trace(K))
    v2 = v ** 2

    # Only the diagonal of the covariance is needed for the beta-binomial
    # profile.  This is the diagonal specialization of the full tensor formula.
    variance = np.dot(u, u) * np.diag(K)
    variance += 2 * np.sum((u * v)[:, None] * Cbib, axis=0)
    variance += np.sum(v2[:, None] * (Diibb - K ** 2), axis=0)
    variance += np.diag(K) * np.sum(v2 * (trace_K - np.diag(K)))
    variance += g ** 2 - np.sum(v2[:, None] * (K ** 2), axis=0)

    tolerance = 2e-10
    if float(np.min(variance)) < -tolerance:
        raise ArithmeticError(f"Negative occupation variance: {variance.min()}")
    variance = np.maximum(variance, 0)
    maximum = mean * (1 - mean)
    if np.any(mean <= 0) or np.any(mean >= 1):
        raise ArithmeticError("Occupation mean left the simplex interior")
    if np.any(variance > maximum * (1 + 2e-7)):
        raise ArithmeticError("Occupation variance exceeds the probability bound")
    variance = np.minimum(variance, maximum * (1 - 1e-12))
    return dict(mean=mean, variance=variance, base=b, linear=u, quadratic=v,
                diagnostics=dict(
                    k=int(k), mean_sum_error=float(abs(mean.sum() - 1)),
                    minimum_variance=float(variance.min()),
                    maximum_variance=float(variance.max()),
                    maximum_variance_fraction=float(np.max(variance / maximum)),
                    expansion="Exact first two moments of b+uA+vA^2."))


def beta_binomial_mean_profile(mean: np.ndarray, variance: np.ndarray,
                               k: int) -> tuple[np.ndarray, dict]:
    """Mean count profile under the marginal two-moment beta closure."""
    counts = np.arange(k + 1)
    profile = np.zeros(k + 1)
    deterministic = 0
    minimum_concentration = math.inf
    for m, var in zip(mean, variance):
        available = m * (1 - m)
        if var <= 1e-13 * available:
            probability = binom.pmf(counts, k, m)
            deterministic += 1
        else:
            concentration = available / var - 1
            if concentration <= 0:
                raise ArithmeticError("Invalid beta concentration")
            minimum_concentration = min(minimum_concentration, concentration)
            a, b = m * concentration, (1 - m) * concentration
            logp = (gammaln(k + 1) - gammaln(counts + 1)
                    - gammaln(k - counts + 1)
                    + betaln(counts + a, k - counts + b) - betaln(a, b))
            probability = np.exp(logp - logsumexp(logp))
        profile += probability
    diagnostics = dict(
        k=int(k), deterministic_beta_limits=deterministic,
        minimum_beta_concentration=(None if math.isinf(minimum_concentration)
                                    else float(minimum_concentration)),
        profile_symbol_sum_error=float(abs(profile.sum() - len(mean))),
        profile_count_sum_error=float(abs(profile @ counts - k)),
        minimum_profile_entry=float(profile.min()),
        qualification=("The beta law is a positive moment closure for each "
                       "marginal occupation probability; it is the approximation "
                       "step, not an identity for the random Markov source."))
    return profile, diagnostics


def iid_mean_profile(probabilities: np.ndarray, k: int) -> np.ndarray:
    """Exact mean count profile for iid draws from fixed probabilities."""
    probabilities = np.asarray(probabilities, dtype=float)
    counts = np.arange(k + 1)
    profile = np.zeros(k + 1)
    for probability in probabilities:
        profile += binom.pmf(counts, k, probability)
    return profile


def trim_profile(profile: np.ndarray, *, weighted_tail_tolerance: float = 1e-9
                 ) -> tuple[np.ndarray, dict]:
    """Drop only a tail whose projected LSA cost bound is negligible."""
    r = np.arange(len(profile))
    weighted = profile * gammaln(r + 1)
    tail = np.cumsum(weighted[::-1])[::-1]
    candidates = np.flatnonzero(tail <= weighted_tail_tolerance)
    stop = int(candidates[0]) if len(candidates) else len(profile)
    stop = max(2, stop)
    retained = profile[:stop]
    diagnostics = dict(
        original_maximum_count=len(profile) - 1,
        retained_maximum_count=len(retained) - 1,
        omitted_symbol_mass=float(profile[stop:].sum()),
        omitted_count_mass=float(profile[stop:] @ r[stop:]),
        omitted_factorial_weight=float(weighted[stop:].sum()),
        weighted_tail_tolerance=weighted_tail_tolerance)
    return retained, diagnostics


def fractional_profile_cost(profile: np.ndarray, k: int, coding_cap: int,
                            tables, *, step: float = 0.08) -> tuple[float, dict]:
    """Evaluate the Appendix-A full LSA mixture at a fractional profile."""
    profile = np.asarray(profile, dtype=float)
    r = np.arange(len(profile))
    grid = np.r_[np.arange(-220.0, -75.0, 4 * step),
                 np.arange(-75.0, 35.0 + step / 2, step)]
    log_widths = _trapezoid_log_weights(grid)
    coarse = np.unique(np.r_[np.arange(0, len(grid), 2), len(grid) - 1])
    log_integrals = []
    maximum_nested_difference = 0.0
    minimum_endpoint_drop = math.inf
    depth_one_difference = None
    for depth in range(1, coding_cap + 1):
        if depth == 1:
            phi = gammaln(r[:, None] + 1) - ((r[:, None] + 1)
                                                      * np.logaddexp(0.0, grid))
        else:
            phi = tables.log_phi_matrix(depth, list(map(int, r)), grid)
        kernel = k * grid + profile @ phi
        peak = float(kernel.max())
        minimum_endpoint_drop = min(
            minimum_endpoint_drop, peak - float(max(kernel[0], kernel[-1])))
        fine = float(logsumexp(kernel + log_widths))
        coarse_value = float(np.log(np.trapezoid(
            np.exp(kernel[coarse] - peak), grid[coarse])) + peak)
        maximum_nested_difference = max(
            maximum_nested_difference, abs(fine - coarse_value) / LN2)
        log_integrals.append(fine)
        if depth == 1:
            calculated = (gammaln(k) - fine) / LN2
            closed = (gammaln(k + profile.sum()) - gammaln(profile.sum())
                      - profile @ gammaln(r + 1)) / LN2
            depth_one_difference = calculated - closed
    cost = (gammaln(k) - logsumexp(log_integrals) + math.log(coding_cap)) / LN2
    diagnostics = dict(
        coding_depth_cap=int(coding_cap), integration_step=step,
        scale_grid_points=len(grid), minimum_endpoint_drop_nats=minimum_endpoint_drop,
        maximum_nested_grid_difference_bits=maximum_nested_difference,
        depth_one_identity_difference_bits=float(depth_one_difference),
        qualification=("The coding-depth mixture and scale integral are retained. "
                       "Nested-grid differences are diagnostics, not certified "
                       "quadrature bounds."))
    return float(cost), diagnostics


def evaluate(d: int, alpha: float, source_depth: int, k: int, coding_cap: int,
             tables, *, source_step: float = 1 / 32, cost_step: float = 0.08,
             row: dict | None = None) -> tuple[dict, dict]:
    q = zipf_law(d, alpha)
    if row is None:
        row = source_row_moments(q, source_depth, tables, step=source_step)
    occupation = finite_occupation_moments(q, k, row)
    profile, profile_diagnostics = beta_binomial_mean_profile(
        occupation["mean"], occupation["variance"], k)
    retained, tail_diagnostics = trim_profile(profile)
    cost, cost_diagnostics = fractional_profile_cost(
        retained, k, coding_cap, tables, step=cost_step)
    result = dict(
        d=int(d), alpha=float(alpha), source_depth=int(source_depth), k=int(k),
        coding_depth_cap=int(coding_cap), predicted_codelength_bits=cost,
        row_moment_diagnostics=row["diagnostics"],
        finite_occupation_diagnostics=occupation["diagnostics"],
        beta_binomial_profile_diagnostics=profile_diagnostics,
        profile_tail_diagnostics=tail_diagnostics,
        lsa_integral_diagnostics=cost_diagnostics)
    return result, row


